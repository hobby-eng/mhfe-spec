#!/usr/bin/env python3
"""Read-only source-link, signature-rewrite and full manifest-ordered splice verification."""

import argparse
import ast
import collections
import hashlib
import json
from pathlib import Path
import re


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def blocks(text):
    starts = [match.start() for match in re.finditer(r"^/--", text, re.M)]
    return [text[start:end] for start, end in zip(starts, [*starts[1:], len(text)])]


def names(block):
    flat = re.sub(r"(def|impl_def|theorem|abbrev)\s*\n\s*", r"\1 ", block)
    result = re.findall(r"^(?:@\[[^\]]*\]\s*)*(?:noncomputable\s+)?"
                        r"(?:def|impl_def|theorem|abbrev|instance)\s+([^\s(:{\[]+)", flat, re.M)
    assert result, block[:300]
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("artifact", type=Path)
    parser.add_argument("core", type=Path)
    parser.add_argument("evidence", type=Path)
    args = parser.parse_args()
    artifact, core, evidence = (p.resolve() for p in [args.artifact, args.core, args.evidence])
    tree = ast.parse((artifact / "tools/make-harness.py").read_text())
    literals = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            target = node.targets[0]
            if isinstance(target, ast.Name) and target.id in {"LINKED", "DYN_TO_GENERIC"}:
                literals[target.id] = ast.literal_eval(node.value)
    assert len(literals["LINKED"]) == 21 and len(literals["DYN_TO_GENERIC"]) == 6
    for relative in literals["LINKED"]:
        path = artifact / "harness" / relative
        assert path.is_symlink() and path.resolve() == (core / relative).resolve(), relative
    rewritten = {}
    for relative, old, new, count in literals["DYN_TO_GENERIC"]:
        text = rewritten.get(relative, (core / relative).read_text())
        assert text.count(old) == count, relative
        rewritten[relative] = text.replace(old, new)
    for relative, text in rewritten.items():
        assert (artifact / "harness" / relative).read_text() == text, relative
    manifest = (artifact / "harness/MANIFEST.txt").read_text()
    count_originals = 0
    for line in manifest.splitlines():
        original = re.fullmatch(r"([a-f0-9]{64})  (.+)", line)
        rewrite = re.fullmatch(r"([a-f0-9]{64})  ([a-f0-9]{64})  (.+)", line)
        if rewrite:
            before, after, relative = rewrite.groups()
            assert sha(core / relative) == before
            assert sha(artifact / "harness" / relative) == after
        elif original:
            digest, relative = original.groups()
            assert sha(core / relative) == digest, relative
            count_originals += 1
    lean = artifact / "lean"
    funs = lean / "MhfeCore/Extraction/Funs.lean"
    trans = lean / "MhfeCore/Assumptions/Translations.lean"
    code = lean / "MhfeCore/Code.lean"
    head, body = funs.read_text().split("namespace mhfe_core\n", 1)
    body, tail = body.rsplit("end mhfe_core", 1)
    extracted, translated = blocks(body), blocks(trans.read_text())
    e_names = {name: block for block in extracted for name in names(block)}
    replacements = {name for block in translated for name in names(block) if name in e_names}
    kept = [("E", block) for block in extracted if not set(names(block)) & replacements]
    additions = [("R" if set(names(block)) & replacements else "T", block) for block in translated]
    all_blocks = {names(block)[0]: (kind, block) for kind, block in [*kept, *additions]}
    assert len(all_blocks) == len(kept) + len(additions) == 174
    order = []
    manifest = (lean / "MANIFEST-code.txt").read_text()
    inputs = {"Funs.lean": funs, "Translations.lean": trans, "Code.lean": code}
    for line in manifest.splitlines():
        digest = re.fullmatch(r"(\S+\.lean)\s+([a-f0-9]{64})", line)
        if digest:
            name, expected = digest.groups()
            assert sha(inputs[name]) == expected, name
        row = re.fullmatch(r"([ETR]) (.+)", line)
        if row:
            kind, name = row.groups()
            assert all_blocks[name][0] == kind
            order.append(name)
    assert len(order) == len(set(order)) == len(all_blocks)
    assert set(order) == set(all_blocks)
    head = head.replace("public import MhfeCore.Extraction.FunsExternal",
                        "public import MhfeCore.Assumptions.FunsExternal")
    banner = ("-- Built by tools/splice.py from MhfeCore/Extraction/Funs.lean (generated by Aeneas) and\n"
              "-- MhfeCore/Assumptions/Translations.lean (written by hand); do not edit.\n")
    prelude = (lean / "MhfeCore/Assumptions/CodePrelude.lean.txt").read_text()
    reconstructed = (banner + head + "namespace mhfe_core\n\n" + prelude +
                     "".join(all_blocks[name][1] for name in order) + "end mhfe_core" + tail)
    assert reconstructed.encode() == code.read_bytes()
    assert all(code.read_text().count(block) == 1 for _, block in all_blocks.values())
    result = {"symlinkEntries": len(literals["LINKED"]), "prescribedRewritePatterns": 6,
              "rewrittenFiles": len(rewritten), "hashedOriginalFiles": count_originals,
              "extractedBlocks": len(extracted), "translatedBlocks": len(translated),
              "replacedBlocks": len(replacements), "finalBlocks": len(order),
              "kinds": dict(collections.Counter(kind for kind, _ in all_blocks.values())),
              "fullCodeByteIdentity": True, "codeSha256": sha(code)}
    (evidence / "provenance-result.json").write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
